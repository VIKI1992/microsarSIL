#!/usr/bin/env python3
"""gen_mcal_cfg.py - generate the symbolic name headers of the virtual MCAL from the MCAL ECUC files.

RTD/AUTOSAR MCAL configuration headers define one macro per configured object, e.g.
  #define DioConf_DioChannel_LED_GREEN   ((Dio_ChannelType)17)
  #define SpiConf_SpiSequence_Seq_Adc    ((Spi_SequenceType)3)
Application and CDD code uses these names; the virtual MCAL has to provide them with the same
values so that channel/sequence/group ids stay consistent with the project.

Usage: gen_mcal_cfg.py -o <outdir> <mcal ecuc arxml...>

One <Mod>_Cfg.h is written per ECUC module found (file name follows the RTD convention:
Mcu_Cfg.h, Dio_Cfg.h, Spi_Cfg.h, Can_43_FLEXCAN_Cfg.h, CDD_I2c_Cfg.h, CDD_Uart_Cfg.h, ...).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ecuc import Container, Ecuc  # noqa: E402

# container definition name -> (id parameter, C type for the cast or None)
ID_PARAMS: Dict[str, Tuple[str, Optional[str]]] = {
    "DioChannel": ("DioChannelId", "Dio_ChannelType"),
    "DioPort": ("DioPortId", "Dio_PortType"),
    "DioChannelGroup": ("DioChannelGroupId", None),
    "PortPin": ("PortPinId", "Port_PinType"),
    "SpiSequence": ("SpiSequenceId", "Spi_SequenceType"),
    "SpiJob": ("SpiJobId", "Spi_JobType"),
    "SpiChannel": ("SpiChannelId", "Spi_ChannelType"),
    "SpiExternalDevice": ("SpiExternalDeviceId", None),
    "PwmChannel": ("PwmChannelId", "Pwm_ChannelType"),
    "IcuChannel": ("IcuChannelId", "Icu_ChannelType"),
    "AdcGroup": ("AdcGroupId", "Adc_GroupType"),
    "AdcChannel": ("AdcChannelId", "Adc_ChannelType"),
    "AdcHwUnit": ("AdcHwUnitId", "Adc_HwUnitType"),
    "GptChannelConfiguration": ("GptChannelId", "Gpt_ChannelType"),
    "McuModeSettingConf": ("McuMode", "Mcu_ModeType"),
    "McuClockSettingConfig": ("McuClockSettingId", "Mcu_ClockType"),
    "McuRamSectorSettingConf": ("McuRamSectionId", "Mcu_RamSectionType"),
    "CanController": ("CanControllerId", "uint8"),
    "CanHardwareObject": ("CanObjectId", "Can_HwHandleType"),
    "I2cChannel": ("I2cChannelId", "uint8"),
    "I2cChannelConfiguration": ("I2cChannelId", "uint8"),
    "UartChannel": ("UartChannelId", "uint8"),
    "MemAccAddressAreaConfiguration": ("MemAccAddressAreaId", "MemAcc_AddressAreaIdType"),
    "FeeBlockConfiguration": ("FeeBlockNumber", "uint16"),
    "LinChannel": ("LinChannelId", "uint8"),
    "CryptoKey": ("CryptoKeyId", "uint32"),
    "CryptoKeyElement": ("CryptoKeyElementId", "uint32"),
    "CryptoDriverObject": ("CryptoDriverObjectId", "uint32"),
}

MODULE_FILES = {
    "Can": "Can_43_FLEXCAN_Cfg.h",
    "I2c": "CDD_I2c_Cfg.h",
    "Uart": "CDD_Uart_Cfg.h",
    "Mcl": "CDD_Mcl_Cfg.h",
    "Crypto": "Crypto_43_HSE_Cfg.h",
    "Mem": "Mem_43_INFLS_Cfg.h",
}


def cident(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("arxml", nargs="+")
    ap.add_argument("-o", "--outdir", required=True)
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--skip", default="Os", help="comma separated modules to ignore (default: Os)")
    args = ap.parse_args(argv)
    skip = {m for m in args.skip.split(",") if m}
    out = Path(args.outdir)
    out.mkdir(parents=True, exist_ok=True)
    ecuc = Ecuc.load(args.arxml)
    total = 0
    for mname, mod in ecuc.modules.items():
        if mname in skip:
            continue
        lines: List[str] = []
        auto: List[str] = []
        for c in mod.all():
            spec = ID_PARAMS.get(c.defn)
            if spec is not None:
                pname, ctype = spec
                v = c.get(pname)
                if v is None:
                    continue
                try:
                    val = int(v, 0)
                except ValueError:
                    continue
                macro = f"{mname}Conf_{c.defn}_{cident(c.name)}"
                lines.append(f"#define {macro} (({ctype}){val}U)" if ctype else f"#define {macro} ({val}U)")
            else:
                # generic: a parameter named <Def>Id makes a symbolic name as well
                v = c.get(f"{c.defn}Id")
                if v is not None:
                    try:
                        val = int(v, 0)
                    except ValueError:
                        continue
                    auto.append(f"#define {mname}Conf_{c.defn}_{cident(c.name)} ({val}U)")
        if not lines and not auto:
            continue
        fname = MODULE_FILES.get(mname, f"{mname}_Cfg.h")
        guard = cident(fname).upper()
        text = [f"/* Generated by microsarSIL tools/gen_mcal_cfg.py from {Path(args.arxml[0]).name} - do not edit. */",
                f"#ifndef SIL_{guard}", f"#define SIL_{guard}", "", '#include "Std_Types.h"', ""]
        text += lines + auto + ["", f"#endif /* SIL_{guard} */", ""]
        content = "\n".join(text)
        p = out / fname
        if not p.exists() or p.read_text(encoding="utf-8") != content:
            p.write_text(content, encoding="utf-8", newline="\n")
        total += len(lines) + len(auto)
        if not args.quiet:
            print(f"{fname}: {len(lines) + len(auto)} symbolic names")
    if not args.quiet:
        print(f"gen_mcal_cfg: {total} symbolic names -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
