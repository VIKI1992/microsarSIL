#!/usr/bin/env python3
"""gen_can_cfg.py - generate SilCan_Cfg.c (virtual CAN driver tables) from the Can ECUC (.arxml).

Reads CanController (id, CanHwChannel, baud rates, Rx/Tx/BusOff processing) and CanHardwareObject
(CanObjectId, type, handle type, id type, hardware object count, CanHwFilter code/mask) containers and
emits:
  - SilCan_Cfg: controllers and hardware objects for sil/mcal/src/Can_43_FLEXCAN.c
  - Can_43_FLEXCAN_Config (the post-build config symbol a project may pass to Can_43_FLEXCAN_Init)
  - the FlexCAN style interrupt handler functions CAN<n>_ORED_IRQHandler, CAN<n>_EnhancedData_IRQHandler,
    CAN<n>_ORED_{0_31,32_63,64_95,96_127}_MB_IRQHandler for every used hardware channel; the OS wrappers
    generated by gen_os_cfg.py call them, they forward to SilCan_Isr().

Usage: gen_can_cfg.py -o <outdir> <ecuc arxml...> [--isr-rx TEMPLATE] [--isr-tx TEMPLATE] [--isr-busoff TEMPLATE]
                      [--channels N,N,...] [--allow-empty]
Templates use {n} for the hardware channel number; defaults are the FlexCAN handler names
CAN{n}_ORED_0_31_MB_IRQHandler (rx), CAN{n}_ORED_32_63_MB_IRQHandler (tx confirmation) and
CAN{n}_ORED_IRQHandler (bus-off). The driver resolves them through the OsIsrSpecialFunctionName of
the OS ISRs (SilOs_IsrByHandler), so they match a MICROSAR project as is.
--channels adds handler functions for FlexCAN channels the OS references but no controller uses.
--allow-empty writes a configuration with zero controllers when the arxml has no Can module.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ecuc import Container, Ecuc  # noqa: E402


def cident(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def hw_number(hw: str) -> int:
    m = re.search(r"(\d+)\s*$", hw or "")
    return int(m.group(1)) if m else 0


def channel_of(ctrl: Container, index: int) -> int:
    return hw_number(ctrl.get("CanHwChannel", f"FLEXCAN_{index}") or f"FLEXCAN_{index}")


def baud_of(ctrl: Container) -> int:
    ref = ctrl.ref1("CanControllerDefaultBaudrate")
    for b in ctrl.sub("CanControllerBaudrateConfig"):
        if ref is None or b.name == ref:
            return b.getint("CanControllerBaudRate", 500) * 1000
    return 500000


def fd_baud_of(ctrl: Container) -> int:
    for b in ctrl.sub("CanControllerBaudrateConfig"):
        fd = b.sub1("CanControllerFdBaudrateConfig")
        if fd is not None:
            return fd.getint("CanControllerFdBaudRate", 0) * 1000
    return 0


def polling(ctrl: Container, key: str) -> int:
    return 1 if (ctrl.get(key, "INTERRUPT") or "").upper() == "POLLING" else 0


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("arxml", nargs="+")
    ap.add_argument("-o", "--outdir", required=True)
    ap.add_argument("--isr-rx", default="CAN{n}_ORED_0_31_MB_IRQHandler")
    ap.add_argument("--isr-tx", default="CAN{n}_ORED_32_63_MB_IRQHandler")
    ap.add_argument("--isr-busoff", default="CAN{n}_ORED_IRQHandler")
    ap.add_argument("--channels", default="", help="extra FlexCAN channel numbers to emit handlers for")
    ap.add_argument("--allow-empty", action="store_true")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)
    ecuc = Ecuc.load(args.arxml)
    if "Can" not in ecuc.modules and not args.allow_empty:
        raise SystemExit(f"no Can module in {args.arxml}; modules: {sorted(ecuc.modules)}")
    mod = ecuc.modules.get("Can")
    ctrls = mod.find("CanController") if mod else []
    hohs = mod.find("CanHardwareObject") if mod else []
    ctrl_idx = {c.name: i for i, c in enumerate(ctrls)}
    o: List[str] = [f"/* Generated by microsarSIL tools/gen_can_cfg.py from {Path(args.arxml[0]).name} - do not edit. */",
                    '#include "SilCan.h"', '#include "Can_43_FLEXCAN.h"', ""]
    for i, h in enumerate(hohs):
        filters = h.sub("CanHwFilter")
        if filters:
            o.append(f"static const SilCan_FilterCfg hoh{i}_filters[] = {{")
            for f in filters:
                idt = {"STANDARD": 0, "EXTENDED": 1}.get((f.get("CanHwFilterIdType") or h.get("CanIdType") or "MIXED").upper(), 2)
                o.append(f"  {{ 0x{f.getint('CanHwFilterCode', 0):X}u, 0x{f.getint('CanHwFilterMask', 0x1FFFFFFF):X}u, {idt}u }},")
            o.append("};")
    o.append("static const SilCan_HohCfg silcan_hohs[] = {")
    for i, h in enumerate(hohs):
        is_tx = 1 if (h.get("CanObjectType", "RECEIVE") or "").upper() == "TRANSMIT" else 0
        is_full = 1 if (h.get("CanHandleType", "BASIC") or "").upper() == "FULL" else 0
        idt = {"STANDARD": 0, "EXTENDED": 1}.get((h.get("CanIdType", "MIXED") or "").upper(), 2)
        ci = ctrl_idx.get(h.ref1("CanControllerRef") or "", 0)
        nf = len(h.sub("CanHwFilter"))
        fd = 1 if h.get("CanFdPaddingValue") not in (None, "") else 0
        fl = f"hoh{i}_filters" if nf else "NULL_PTR"
        o.append(f'  {{ "{h.name}", {h.getint("CanObjectId", i)}u, {is_tx}u, {is_full}u, {idt}u, {ci}u, '
                 f'{max(1, h.getint("CanHwObjectCount", 1))}u, {nf}u, {fl}, {fd}u }},')
    if not hohs:
        o.append('  { "none", 0u, 0u, 0u, 2u, 0u, 1u, 0u, NULL_PTR, 0u },')
    o.append("};")
    o.append("static const SilCan_ControllerCfg silcan_controllers[] = {")
    channels: List[int] = []
    for i, c in enumerate(ctrls):
        n = channel_of(c, i)
        if n not in channels:
            channels.append(n)
        o.append(f'  {{ "{c.name}", {c.getint("CanControllerId", i)}u, {n}u, {baud_of(c)}u, {fd_baud_of(c)}u, '
                 f'{polling(c, "CanRxProcessing")}u, {polling(c, "CanTxProcessing")}u, {polling(c, "CanBusoffProcessing")}u, '
                 f'"{args.isr_rx.format(n=n)}", "{args.isr_tx.format(n=n)}", "{args.isr_busoff.format(n=n)}" }},')
    if not ctrls:
        o.append('  { "none", 0u, 0u, 500000u, 0u, 1u, 1u, 1u, "", "", "" },')
    o.append("};")
    o.append(f"const SilCan_Config SilCan_Cfg = {{ {len(ctrls)}u, silcan_controllers, {len(hohs)}u, silcan_hohs }};")
    o.append("const Can_43_FLEXCAN_ConfigType Can_43_FLEXCAN_Config = { 0u };")
    o.append("")
    o.append("/* FlexCAN interrupt handler functions (targets of the Os_Isr_* wrappers) */")
    for n in [int(x) for x in args.channels.split(",") if x.strip()]:
        if n not in channels:
            channels.append(n)
    for n in channels:
        idx = next((i for i, c in enumerate(ctrls) if channel_of(c, i) == n), 0xFF)
        o.append(f"void CAN{n}_ORED_IRQHandler(void);")
        o.append(f"void CAN{n}_ORED_IRQHandler(void) {{ SilCan_Isr({idx}u, SILCAN_ISR_BUSOFF); }}")
        o.append(f"void CAN{n}_EnhancedData_IRQHandler(void);")
        o.append(f"void CAN{n}_EnhancedData_IRQHandler(void) {{ SilCan_Isr({idx}u, SILCAN_ISR_RXFIFO); }}")
        for grp in ("0_31", "32_63", "64_95", "96_127"):
            o.append(f"void CAN{n}_ORED_{grp}_MB_IRQHandler(void);")
            o.append(f"void CAN{n}_ORED_{grp}_MB_IRQHandler(void) {{ SilCan_Isr({idx}u, SILCAN_ISR_MB); }}")
    content = "\n".join(o) + "\n"
    out = Path(args.outdir)
    out.mkdir(parents=True, exist_ok=True)
    p = out / "SilCan_Cfg.c"
    if not p.exists() or p.read_text(encoding="utf-8") != content:
        p.write_text(content, encoding="utf-8", newline="\n")
    if not args.quiet:
        print(f"gen_can_cfg: {len(ctrls)} controllers, {len(hohs)} hardware objects, channels {channels} -> {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
